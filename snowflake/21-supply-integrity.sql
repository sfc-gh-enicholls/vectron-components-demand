-- =====================================================================
-- 21-supply-integrity.sql — supply checks, composed into V_INTEGRITY_ALL
-- =====================================================================
-- Follows the house pattern: each domain owns a check view and
-- V_INTEGRITY_ALL UNIONs them. NOTE: re-running 16-hierarchies.sql
-- redefines V_INTEGRITY_ALL WITHOUT supply; run this file after it.
-- Tolerances are relative (GREATEST(1e-6, |x| * 1e-9)): a fixed cent is
-- below double precision at 1e8 units.
-- =====================================================================
USE DATABASE VECTRON_DEMAND;
USE SCHEMA APP;

CREATE OR REPLACE VIEW V_INTEGRITY_SUPPLY AS
-- The bridge: SKU units must reconcile to series units, per customer-week.
SELECT 'supply_bridge_reconciles' AS CHECK_NAME, COUNT(*) AS VIOLATIONS
FROM (
  SELECT s.CUSTOMER_ID, d.WEEK_ID, SUM(d.PLAN_UNITS) AS SERIES_UNITS
  FROM CORE.FACT_DEMAND_PLAN d JOIN CORE.DIM_SERIES s ON s.SERIES_ID = d.SERIES_ID
  GROUP BY 1, 2
) a
FULL JOIN (
  SELECT CUSTOMER_ID, WEEK_ID, SUM(DEMAND_UNITS) AS SKU_UNITS
  FROM APP.V_SKU_DEMAND WHERE PLAN_SOURCE = 'COMMITTED' GROUP BY 1, 2
) b ON b.CUSTOMER_ID = a.CUSTOMER_ID AND b.WEEK_ID = a.WEEK_ID
WHERE a.CUSTOMER_ID IS NULL OR b.CUSTOMER_ID IS NULL
   OR ABS(a.SERIES_UNITS - b.SKU_UNITS) > GREATEST(1e-6, ABS(a.SERIES_UNITS) * 1e-9)
UNION ALL
SELECT 'supply_mix_sums_to_one', COUNT(*)
FROM (SELECT 1 FROM CORE.CUSTOMER_FORMAT_MIX
      GROUP BY CUSTOMER_ID, CATEGORY_ID, CALENDAR_MONTH HAVING ABS(SUM(SHARE) - 1) > 1e-9)
UNION ALL
-- Every SKU-customer has a source, and own-site SKUs have a line.
SELECT 'supply_sku_unrouted', COUNT(*)
FROM CORE.DIM_SKU k CROSS JOIN CORE.DIM_CUSTOMER m
LEFT JOIN CORE.SKU_CUSTOMER_SOURCE s ON s.SKU_ID = k.SKU_ID AND s.CUSTOMER_ID = m.CUSTOMER_ID
WHERE s.SITE_ID IS NULL OR (s.SITE_ID <> 'SITE-OCP' AND s.LINE_ID IS NULL)
UNION ALL
-- Lot-for-lot netting must hold the balance at or above safety stock.
SELECT 'supply_balance_below_safety', COUNT(*)
FROM APP.V_NET_REQUIREMENT
WHERE PLAN_SOURCE = 'COMMITTED'
  AND PROJECTED_BALANCE_UNITS < SAFETY_STOCK_UNITS
      - GREATEST(1e-6, ABS(SAFETY_STOCK_UNITS) * 1e-9)
UNION ALL
-- Every requested case is accounted for exactly once.
SELECT 'supply_order_mass_balance', COUNT(*)
FROM CORE.FACT_SUPPLY_PLAN
WHERE ABS(REQUESTED_UNITS - (LIQUID_SHORT_UNITS + PRODUCED_UNITS + UNMET_UNITS))
        > GREATEST(1e-3, REQUESTED_UNITS * 1e-9)
   OR ABS(PRODUCED_UNITS - (ON_TIME_UNITS + LATE_UNITS))
        > GREATEST(1e-3, PRODUCED_UNITS * 1e-9)
UNION ALL
-- Allocation can never exceed what the customer asked for.
SELECT 'supply_allocation_exceeds_demand', COUNT(*)
FROM CORE.FACT_SUPPLY_PLAN
WHERE ON_TIME_UNITS + LATE_UNITS > REQUESTED_UNITS + GREATEST(1e-3, REQUESTED_UNITS * 1e-9)
   OR LIQUID_SHORT_UNITS < -1e-3 OR UNMET_UNITS < -1e-3 OR LATE_UNITS < -1e-3
UNION ALL
-- The solved plan never runs a line beyond its effective capacity.
SELECT 'supply_line_over_capacity', COUNT(*)
FROM CORE.FACT_SUPPLY_LINE_WEEK lw
JOIN CORE.DIM_LINE l ON l.LINE_ID = lw.LINE_ID
WHERE lw.PRODUCED_UNITS > lw.CAPACITY_UNITS * (1 - l.CHANGEOVER_LOSS) + 1e-3
UNION ALL
-- No dry-goods item is drawn below zero.
SELECT 'supply_dry_goods_negative', COUNT(*)
FROM CORE.FACT_SUPPLY_ITEM_WEEK WHERE STOCK_UNITS < -1e-3
UNION ALL
-- A solve that is not stale must have solved exactly the live orders.
SELECT 'supply_solve_matches_live_orders', COUNT(*)
FROM APP.V_SUPPLY_SOLVE_STATUS st
JOIN (SELECT PLAN_SOURCE, SUM(REQUESTED_UNITS) AS SOLVED FROM CORE.FACT_SUPPLY_PLAN GROUP BY 1) sp
  ON sp.PLAN_SOURCE = st.PLAN_SOURCE
JOIN (SELECT PLAN_SOURCE, SUM(ORDER_UNITS) AS LIVE FROM APP.V_PLANNED_ORDERS GROUP BY 1) po
  ON po.PLAN_SOURCE = st.PLAN_SOURCE
WHERE NOT st.IS_STALE AND ABS(sp.SOLVED - po.LIVE) > GREATEST(1e-3, po.LIVE * 1e-9)
UNION ALL
-- One run per source, and every result row belongs to it.
SELECT 'supply_run_orphan', COUNT(*)
FROM CORE.FACT_SUPPLY_PLAN sp
LEFT JOIN CORE.FACT_SUPPLY_SOLVE_RUN r ON r.RUN_ID = sp.RUN_ID AND r.PLAN_SOURCE = sp.PLAN_SOURCE
WHERE r.RUN_ID IS NULL
UNION ALL
-- Once the committed plan is solved, every agent proposal carries a supply
-- signal (22-supply-signal.sql), or the reconciliation silently omits supply.
SELECT 'supply_signal_coverage', COUNT(*)
FROM CORE.FACT_AGENT_PROPOSAL p
LEFT JOIN CORE.FACT_PROPOSAL_SIGNAL ps
  ON ps.PROPOSAL_ID = p.PROPOSAL_ID AND ps.SOURCE_ID = 'supply_plan'
WHERE ps.PROPOSAL_ID IS NULL
  AND EXISTS (SELECT 1 FROM CORE.FACT_SUPPLY_SOLVE_RUN WHERE PLAN_SOURCE = 'COMMITTED')
UNION ALL
-- And that signal must be rebuilt from the CURRENT committed solve, not an
-- older one (SP_REFRESH_SUPPLY_SIGNAL stamps the run it reflects).
SELECT 'supply_signal_current', COUNT(*)
FROM CORE.FACT_SUPPLY_SOLVE_RUN
WHERE PLAN_SOURCE = 'COMMITTED'
  AND (SIGNAL_REFRESHED_AT IS NULL OR SIGNAL_REFRESHED_AT < SOLVED_AT)
UNION ALL
-- The planned-order cache, where its version is current, must equal the live
-- view order for order (count and units per source).
SELECT 'supply_order_cache_matches_live', COUNT(*)
FROM CORE.SUPPLY_ORDER_CACHE_VERSION cv
JOIN APP.V_PLAN_VERSION v ON v.PLAN_SOURCE = cv.PLAN_SOURCE AND v.PLAN_VERSION = cv.PLAN_VERSION
LEFT JOIN (SELECT PLAN_SOURCE, COUNT(*) AS N, SUM(ORDER_UNITS) AS UNITS
           FROM CORE.SUPPLY_ORDER_CACHE GROUP BY 1) c ON c.PLAN_SOURCE = cv.PLAN_SOURCE
LEFT JOIN (SELECT PLAN_SOURCE, COUNT(*) AS N, SUM(ORDER_UNITS) AS UNITS
           FROM APP.V_PLANNED_ORDERS GROUP BY 1) l ON l.PLAN_SOURCE = cv.PLAN_SOURCE
WHERE COALESCE(c.N, 0) <> COALESCE(l.N, 0)
   OR ABS(COALESCE(c.UNITS, 0) - COALESCE(l.UNITS, 0)) > GREATEST(1e-3, ABS(COALESCE(l.UNITS, 0)) * 1e-9)
UNION ALL
-- Inside a dry good's lead time the supplier cannot flex: deliveries in
-- weeks 1..LEAD_WEEKS are the base rate, and never above the flexed rate.
SELECT 'supply_dry_lead_time_respected', COUNT(*)
FROM APP.V_DRY_GOODS_DELIVERY dl
JOIN CORE.DIM_DRY_GOOD dg ON dg.ITEM_ID = dl.ITEM_ID
WHERE (dl.WEEK_NO <= dg.LEAD_WEEKS AND dl.DELIVERY_UNITS <> dg.BASE_SUPPLY_UNITS_WEEK)
   OR dg.BASE_SUPPLY_UNITS_WEEK > dg.SUPPLY_UNITS_WEEK
   OR dg.BASE_SUPPLY_UNITS_WEEK IS NULL
UNION ALL
SELECT 'supply_no_nulls', COUNT(*)
FROM CORE.FACT_SUPPLY_PLAN
WHERE REQUESTED_UNITS IS NULL OR PRODUCED_UNITS IS NULL OR ON_TIME_UNITS IS NULL
   OR LATE_UNITS IS NULL OR UNMET_UNITS IS NULL OR LIQUID_SHORT_UNITS IS NULL;

CREATE OR REPLACE VIEW V_INTEGRITY_ALL AS
SELECT CHECK_NAME, VIOLATIONS FROM V_DATA_INTEGRITY
UNION ALL
SELECT CHECK_NAME, VIOLATIONS FROM V_INTEGRITY_CALLOFFS
UNION ALL
SELECT CHECK_NAME, VIOLATIONS FROM V_INTEGRITY_IHS
UNION ALL
SELECT CHECK_NAME, VIOLATIONS FROM V_INTEGRITY_SERVICE
UNION ALL
SELECT CHECK_NAME, VIOLATIONS FROM V_INTEGRITY_ALLOCATION
UNION ALL
SELECT CHECK_NAME, VIOLATIONS FROM V_INTEGRITY_VALUE
UNION ALL
SELECT CHECK_NAME, VIOLATIONS FROM V_INTEGRITY_DUTY
UNION ALL
SELECT CHECK_NAME, VIOLATIONS FROM V_INTEGRITY_SIGNALS
UNION ALL
SELECT CHECK_NAME, VIOLATIONS FROM V_INTEGRITY_CYCLES
UNION ALL
SELECT CHECK_NAME, VIOLATIONS FROM V_INTEGRITY_APPROVALS
UNION ALL
SELECT CHECK_NAME, VIOLATIONS FROM V_INTEGRITY_FORMULAS
UNION ALL
SELECT CHECK_NAME, VIOLATIONS FROM V_INTEGRITY_HIERARCHIES
UNION ALL
SELECT CHECK_NAME, VIOLATIONS FROM V_INTEGRITY_SUPPLY;
